type LangKey = keyof typeof UZ;
type LangDict = typeof UZ;

const DICTS: Record<string, LangDict> = { uz: UZ, ru: RU };

interface LangCtx {
  lang: string;
  setLang: (l: string) => void;
  t: (key: LangKey) => string;
  tp: (key: LangKey, n: number) => string;
}

/**
 * Russian nouns change after numbers (1 сессия, 2 сессии, 5 сессий), so RU values
 * may hold "one|few|many" forms. Uzbek keeps one form. Without n the "many" form is used.
 */
function pluralForm(value: string, lang: string, n?: number): string {
  if (typeof value !== 'string' || !value.includes('|')) return value;
  const forms = value.split('|');
  if (lang !== 'ru') return forms[0];
  if (n == null || !Number.isInteger(Math.abs(Number(n)))) return forms[2] ?? forms[forms.length - 1];
  const a = Math.abs(Number(n)), d = a % 10, h = a % 100;
  const idx = d === 1 && h !== 11 ? 0 : d >= 2 && d <= 4 && (h < 12 || h > 14) ? 1 : 2;
  return forms[idx] ?? forms[forms.length - 1];
}

const LangContext = React.createContext<LangCtx>({
  lang: 'uz',
  setLang: () => {},
  t: (k) => UZ[k] ?? k,
  tp: (k, n) => String(UZ[k] ?? k).split('|')[0].replace('{n}', String(n)),
});

export function LangProvider({ children }) {
  const [lang, setLangState] = React.useState(() => localStorage.getItem('alpha_lang') || 'uz');

  function setLang(l: string) {
    setLangState(l);
    localStorage.setItem('alpha_lang', l);
  }

  function t(key: LangKey): string {
    return pluralForm(DICTS[lang]?.[key] ?? UZ[key] ?? key, lang);
  }

  /** Word for a count: tp('session_sfx', 5) → "сессий"; fills a {n} slot when present. */
  function tp(key: LangKey, n: number): string {
    return pluralForm(DICTS[lang]?.[key] ?? UZ[key] ?? key, lang, n).replace('{n}', String(n));
  }

  return <LangContext.Provider value={{ lang, setLang, t, tp }}>{children}</LangContext.Provider>;
}

export function useT() {
  return React.useContext(LangContext);
}
